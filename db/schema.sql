-- 1. 起名历史表
create table if not exists public.name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,          -- 用户输入的起名需求
  name_result text not null,               -- AI 生成的完整方案（Markdown 原文）
  model_name text not null,                -- 使用的模型，例如 doubao · ep-2024xxxx
  created_at timestamptz not null default now()
);

-- 2. 按时间倒序查历史更快
create index if not exists name_history_created_at_idx
  on public.name_history (created_at desc);

-- 3. 开启行级安全（RLS）
alter table public.name_history enable row level security;

-- 4. 策略：允许匿名 key 读取历史（前端展示最近记录）
drop policy if exists "name_history_select_anon" on public.name_history;
create policy "name_history_select_anon"
  on public.name_history
  for select
  to anon, authenticated
  using (true);

-- 5. 策略：允许匿名 key 写入（仅按实验要求放开；正式项目建议改用 service_role 写入）
drop policy if exists "name_history_insert_anon" on public.name_history;
create policy "name_history_insert_anon"
  on public.name_history
  for insert
  to anon, authenticated
  with check (true);

